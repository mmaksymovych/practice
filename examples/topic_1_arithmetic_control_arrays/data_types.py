# --- НАЙБІЛЬШ ВИКОРИСТОВУВАНІ ТИПИ ДАНИХ ---

# Рядок (str) - Текстові дані
name = "Alice"  # Послідовність символів

# Ціле число (int) - Цілі числа без дробової частини
age = 25  # Без десяткової коми

# Дійсне число (float) - Числа з десятковою комою
price = 19.99  # Містить десяткову кому

# Булевий тип (bool) - Значення Істина або Хибність
is_active = True  # Представляє умову істина/хибність

# Список (list) - Впорядкована, змінювана колекція
fruits = ["apple", "banana", "cherry"]  # Можна змінювати
vegetables = ['cucumber', 'tomato', 'lettuce']  # Ще один приклад списку

# Вкладений список - список списків
food = [fruits, vegetables]  # Список, що містить інші списки


# Кортеж (tuple) - Впорядкована, незмінювана колекція
coordinates = (10.0, 20.0)  # Не можна змінити після створення

# Словник (dict) - Пари ключ-значення
person = {
    "name": "Alice",      # ключ: значення
    "age": 25,            # зручно для зберігання властивостей об'єкта
    "maried": False
}  # Відображення ключ-значення

# Множина (set) - Невпорядкована колекція унікальних елементів
unique_numbers = {1, 2, 3, 4, 4}  # Дублікати автоматично видаляються

# --- МЕНШ ПОШИРЕНІ, АЛЕ КОРИСНІ ТИПИ ДАНИХ ---

# Комплексне число (complex) - Числа з дійсною та уявною частинами
z = 2 + 3j  # Використовується в складних математичних операціях

# Діапазон (range) - Послідовність чисел
numbers = range(5)  # Генерує числа від 0 до 4

# Заморожена множина (frozenset) - Незмінювана множина
immutable_set = frozenset({1, 2, 3})  # Не можна змінити

# Байти (bytes) - Незмінювана послідовність байтів
byte_data = b"hello"  # Використовується для бінарних даних

# Масив байтів (bytearray) - Змінювана послідовність байтів
mutable_bytes = bytearray(b"hello")  # Можна змінювати

# Перегляд пам'яті (memoryview) - Представлення байтової послідовності
mem_view = memoryview(byte_data)  # Ефективна робота з бінарними даними

# NoneType (None) - Представляє відсутність значення
result = None  # Використовується коли змінна не має значення