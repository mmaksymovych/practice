# === ЦИКЛИ ТА УМОВНІ КОНСТРУКЦІЇ ===

# --- Цикл for ---
# Виводить числа від 0 до 5
for i in [0, 1, 2, 3, 4, 5]:
    print(i)


# --- Цикл while ---
# Виконується доки умова істинна
n = 1
while n <= 5:
    print(n)
    n += 1  # Збільшуємо лічильник на 1


# --- Цикл з оператором break ---
# Цикл зупиняється при досягненні певної умови
for i in range(1, 10):
    if i == 5:
        break  # Зупиняється коли i дорівнює 5
    print(i)


# --- Цикл з оператором continue ---
# Пропускає ітерацію при певній умові
for i in range(1, 6):
    if i == 3:
        continue  # Пропускає коли i дорівнює 3
    print(i)


# --- Ітерація по списку ---
fruits = ["apple", "banana", "cherry"]

# Виводимо кожен елемент списку
for fruit in fruits:
    print(fruit)


# --- Умовні конструкції в циклі ---
numbers = [1, 2, 3, 4, 5]

# Перевіряємо кожне число на парність
for num in numbers:
    if num % 2 == 0:
        print(f"{num} is even")  # Парне число
    else:
        print(f"{num} is odd")   # Непарне число